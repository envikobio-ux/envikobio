// 获取所有文章分类统计
export function getCategoryStats() {
  return ARTICLE_CATEGORIES.map(cat => ({
    ...cat,
    count: TECH_ARTICLES.filter(a => a.category === cat.slug).length,
  }));
}

// 根据分类获取文章
export function getArticlesByCategory(category: string) {
  return TECH_ARTICLES.filter(a => a.category === category);
}

// 根据产品CAS获取关联文章
export function getArticlesByProduct(cas: string) {
  return TECH_ARTICLES.filter(a => a.relatedProducts.includes(cas));
}

// 根据slug获取文章
export function getArticleBySlug(slug: string) {
  return TECH_ARTICLES.find(a => a.slug === slug);
}

// 搜索文章
export function searchArticles(query: string) {
  const lowerQuery = query.toLowerCase();
  return TECH_ARTICLES.filter(a => 
    a.title.toLowerCase().includes(lowerQuery) ||
    a.excerpt.toLowerCase().includes(lowerQuery) ||
    a.keywords.some(k => k.toLowerCase().includes(lowerQuery)) ||
    a.tags.some(t => t.toLowerCase().includes(lowerQuery))
  );
}